/**
 * Converts Arabic-Indic (٠-٩) and Extended Arabic-Indic (۰-۹) digits to Western ASCII digits
 * and strips invisible bidirectional formatting characters.
 */
export function normalizeLessonThreeDigits(value: string): string {
  return value
    .replace(/[\u200e\u200f\u202a-\u202e\u2066-\u2069]/gu, '')
    .replace(/[٠-٩]/gu, digit => String(digit.charCodeAt(0) - 0x0660))
    .replace(/[۰-۹]/gu, digit => String(digit.charCodeAt(0) - 0x06f0))
}

/**
 * Safely normalizes a numeric input string into canonical digits.
 * Accepts:
 * 1) A contiguous integer without separators (e.g. `700000`, `٧٠٠٠٠٠`, `۷۰۰۰۰۰`), or
 * 2) A positive integer grouped from the right into 3-digit periods separated by a single
 *    comma (`,`, `،`, `٬`) or horizontal space (e.g. `700,000`, `٧٠٠،٠٠٠`, `700 000`).
 * Outer whitespace is trimmed safely.
 * Returns `null` for empty inputs, malformed groupings (such as `70,00,00` or `7,0,0,0,0,0`),
 * repeated commas (`700,,000`), underscores (`7_00_000`), leading/trailing separators,
 * decimals, signs, letters, or invalid leading zeros on multi-digit numbers.
 */
export function normalizeLessonThreeNumberInput(value: string): string | null {
  const normalized = normalizeLessonThreeDigits(value).trim()
  if (!normalized) return null
  const isContiguousInteger = /^(?:0|[1-9][0-9]*)$/u.test(normalized)
  const isThreeDigitGroupedInteger =
    /^[1-9][0-9]{0,2}(?:(?:[ \t]+|[ \t]*[,،٬][ \t]*)[0-9]{3})+$/u.test(normalized)
  if (!isContiguousInteger && !isThreeDigitGroupedInteger) return null
  const digitsOnly = normalized.replace(/[ \t,،٬]+/gu, '')
  if (digitsOnly.length > 1 && digitsOnly.startsWith('0')) return null
  return digitsOnly
}

/**
 * Normalizes Arabic verbal answers so equivalent orthographic forms
 * (such as مليونًا/مليوناً/مليونا or ثلاثمئة/ثلاثمائة) match reliably.
 */
export function normalizeLessonThreeArabicText(value: string): string {
  return normalizeLessonThreeDigits(value)
    .normalize('NFKC')
    .replace(/[\u064b-\u065f\u0670\u0640]/gu, '')
    .replace(/[أإآ]/gu, 'ا')
    .replace(/ة/gu, 'ه')
    .replace(/ى/gu, 'ي')
    .replace(/مائتان/gu, 'مئتان')
    .replace(/مائتا/gu, 'مئتا')
    .replace(/مائه/gu, 'مئه')
    .replace(/[.,،؛:!؟"'()[\]]/gu, ' ')
    .replace(/\s+/gu, ' ')
    .trim()
}

/**
 * Evaluates a student response against an expected answer (numeric or verbal).
 */
export function isLessonThreeAnswerCorrect(userInput: string, expectedAnswer: string): boolean {
  const expectedNumber = normalizeLessonThreeNumberInput(expectedAnswer)
  if (expectedNumber !== null) {
    const actualNumber = normalizeLessonThreeNumberInput(userInput)
    return actualNumber !== null && actualNumber === expectedNumber
  }
  const actualText = normalizeLessonThreeArabicText(userInput)
  const expectedText = normalizeLessonThreeArabicText(expectedAnswer)
  return actualText.length > 0 && actualText === expectedText
}

export function evaluateFinalQuestion3(question: NaturalNumbersQuestion, userInput: string): boolean {
  if (question.type === 'choice') {
    return userInput.trim() === question.answer.trim()
  }
  return isLessonThreeAnswerCorrect(userInput, question.answer)
}

