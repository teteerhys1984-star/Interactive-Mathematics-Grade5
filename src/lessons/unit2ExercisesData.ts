  `القسم: ${element.section}. المصدر: الكتاب، ص ${element.page}.${element.figure ? ` الرسم المطبوع: ${element.figure}` : ''}${pitfall ? ` خطأ شائع: ${pitfall}` : ''}${element.note ? ` ملاحظة تحريرية: ${element.note}` : ''} خطوات الحل والتفسير إضافات تعليمية من المنصة، وليست مطبوعة كحل في الكتاب.`

export const unit2ExercisesTeacherEntries: TeacherEntry[] = unit2ExercisesSourceElements.flatMap((element) => {
  if (!element.branches?.length) {
    return [{ id: `t-${element.id}`, title: element.section, prompt: teacherSafe(element.prompt), answer: teacherSafe(element.answer), source: { type: 'textbook', page: element.page }, reasoning: solutionReasoning(element), note: sourceNote(element, element.pitfall) }]
  }
  const overview: TeacherEntry = { id: `t-${element.id}`, title: `${element.section} · نظرة عامة`, prompt: teacherSafe(element.prompt), answer: teacherSafe(element.answer), source: { type: 'textbook', page: element.page }, reasoning: solutionReasoning(element), note: sourceNote(element, element.pitfall) }
  return [overview, ...element.branches.map((item): TeacherEntry => ({ id: `t-${item.id}`, title: `${element.section} · ${item.label}`, prompt: teacherSafe(item.prompt), answer: teacherSafe(item.answer), source: { type: 'textbook', page: element.page }, reasoning: solutionReasoning(item), note: sourceNote(element, item.pitfall ?? element.pitfall) }))]
})

