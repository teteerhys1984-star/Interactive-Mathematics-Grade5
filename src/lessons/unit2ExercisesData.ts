export const unit2ExercisesSourceBranches = unit2ExercisesSourceElements.flatMap((element) => element.branches ?? [])
export function flattenUnit2ExercisesCoverageIds(): string[] {
  return unit2ExercisesSourceElements.flatMap((element) => [element.id, ...(element.branches ?? []).map((branch) => branch.id)])
}
export function findUnit2ExercisesElement(id: string): SourceElement {
  const element = unit2ExercisesSourceElements.find((entry) => entry.id === id)
  if (!element) throw new Error(`Unknown unit-2-exercises source id: ${id}`)
  return element
}

