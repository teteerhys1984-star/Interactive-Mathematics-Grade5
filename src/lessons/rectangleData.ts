const flattenRich = (content: RichContent): string => content.map((run) => run.text).join('')
const difficultyLabels = { basic: 'أساسي', medium: 'متوسط', advanced: 'متقدّم', thinking: 'تفكير' } as const
function describeQuestion(question: QuestionDefinition): string {
  const prompt = flattenRich(question.prompt)
  switch (question.type) {
    case 'single-choice':
    case 'multi-select':
      return `${prompt} الخيارات: ${question.options.map((option) => flattenRich(option.label)).join(' / ')}.`
    case 'true-false':
      return `${prompt} (صح أم خطأ)`
    case 'ordering':
      return `${prompt} العناصر: ${question.items.map((item) => flattenRich(item.label)).join(' / ')}.`
    case 'matching':
      return `${prompt} العمود الأول: ${question.left.map((item) => flattenRich(item.label)).join(' / ')}. العمود الثاني: ${question.right.map((item) => flattenRich(item.label)).join(' / ')}.`
    case 'error-analysis':
      return `${prompt} عمل الطالب: ${flattenRich(question.studentWork)}. التشخيصات: ${question.diagnoses.map((item) => flattenRich(item.label)).join(' / ')}.${question.corrections ? ` التصحيحات: ${question.corrections.map((item) => flattenRich(item.label)).join(' / ')}.` : ''}`
    default:
      return prompt
  }
}
